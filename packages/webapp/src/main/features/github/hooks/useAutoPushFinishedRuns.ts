/**
 * "Push generated code to GitHub": when a Spec-Driven run of the open project
 * finishes with its whole output, push it to the project's linked repository and
 * branch, as the run card's Push to GitHub would (merged with newer commits, a
 * conflict left on its own branch). Mounted once, by the GitHub menu, next to
 * useGitHubAutosave.
 */
import { useEffect, useRef } from 'react';
import { toast } from 'react-toastify';
import i18n from '../../../shared/i18n';
import { useAppDispatch } from '../../../app/store/hooks';
import { useProject } from '../../../app/hooks/useProject';
import { getProjectGitHubLink } from '../../../shared/services/storage/projectGitHubLink';
import { SPEC_DRIVEN_RUN_SUCCEEDED_EVENT, type SpecDrivenRunSucceededDetail } from '../../spec-driven';
import { pushRunToRepo } from './useSpecDrivenGithubPush';

/** Runs already pushed in this tab: one automatic push per run, whichever surface reports it. */
const pushedRuns = new Set<string>();

export function useAutoPushFinishedRuns({ githubSession }: { githubSession: string | null }): void {
  const { currentProject, loadProject } = useProject();
  const dispatch = useAppDispatch();
  const live = useRef({ currentProject, loadProject, githubSession });
  live.current = { currentProject, loadProject, githubSession };

  useEffect(() => {
    const onRunSucceeded = (event: Event) => {
      const { projectId, runId } = (event as CustomEvent<SpecDrivenRunSucceededDetail>).detail;
      const { currentProject: project, loadProject: load, githubSession: session } = live.current;
      const link = getProjectGitHubLink(projectId);
      if (!project || project.id !== projectId || !link?.pushRuns || pushedRuns.has(runId)) return;
      if (!session) {
        toast.info(i18n.t('github.pushRuns.connectFirst', {
          defaultValue: 'Connect GitHub in this tab to push the generated code; the run card can push it later.',
        }));
        return;
      }
      pushedRuns.add(runId);
      void pushRunToRepo(
        { project, runId, githubSession: session, linkedRepo: link, loadProject: load, dispatch, automatic: true },
        {
          useExisting: true,
          owner: link.owner,
          repoName: link.repo,
          branch: link.branch,
          isPrivate: true,
          commitMessage: i18n.t('github.pushRuns.commitMessage', {
            defaultValue: 'Add the code generated by the BESSER Spec-Driven Agent',
          }),
          pushMode: 'commit',
        },
      );
    };
    window.addEventListener(SPEC_DRIVEN_RUN_SUCCEEDED_EVENT, onRunSucceeded);
    return () => window.removeEventListener(SPEC_DRIVEN_RUN_SUCCEEDED_EVENT, onRunSucceeded);
  }, [dispatch]);
}

/** Forget the runs pushed so far (tests). */
export function resetAutoPushedRunsForTests(): void {
  pushedRuns.clear();
}
